// PACKTOOK V6.7 — offline assertions for the read-only live deployment probe.
import assert from "node:assert/strict";
import {customerEvidence,marketingEvidence,statusEvidence,decide} from "./probe-free-deployment.mjs";
const customerHTML='<html><head><meta name="robots" content="noindex,nofollow"></head><body><div>PRODUCTION BETA</div><div id="publicSignupForm"></div><div id="publicSignupFinish"></div><script src="app.js?v=6.6.0"></script></body></html>';
const marketingHTML='<div>REGISTRATION &amp; PAYMENT NOT OPEN</div><link rel="x" href="howto-ready.webp?v=6.5.6"><meta name="robots" content="noindex,nofollow">';
const customer={http:200,...customerEvidence(customerHTML)};
const marketing={http:200,...marketingEvidence(marketingHTML)};
const disabled={http:200,...statusEvidence({result:{enabled:false,accessEnabled:false,policyVersion:"2026-11-v1",freeVideosPerMonth:20,freeDevices:1}},200)};
const base={customer,marketing,status:disabled};
assert.equal(decide(base,{expectV66:true}).pass,true);
assert.equal(customer.v66Script,true);
assert.equal(customer.hasSignupForm,true);
assert.equal(customer.hasVerifyStep,true);
assert.equal(marketing.prelaunchNotice,true);
assert.equal(disabled.publicSignupEnabled,false);
console.log("PASS: deployed V6.6 Customer + disabled Public STATUS is safe (not Public approval)");
const old={...base,customer:{...customer,v66Script:false,hasSignupForm:false}};
assert(decide(old,{expectV66:true}).reasons.includes("CUSTOMER_V66_NOT_DEPLOYED"));
assert(decide(old,{expectV66:true}).reasons.includes("CUSTOMER_SIGNUP_HTML_NOT_DEPLOYED"));
const notDeployed={...base,status:{http:404,...statusEvidence(null,404)}};
assert(decide(notDeployed,{expectV66:true}).reasons.includes("PUBLIC_STATUS_CALLABLE_NOT_DEPLOYED_OR_UNVERIFIED"));
const wronglyEnabled={...base,status:{...disabled,publicSignupEnabled:true}};
assert(decide(wronglyEnabled,{expectV66:true}).reasons.includes("UNEXPECTED_PUBLIC_FLAG_ENABLED"));
const paidAccessEnabled={...base,status:{...disabled,publicAccessEnabled:true}};
assert(decide(paidAccessEnabled,{expectV66:true}).reasons.includes("UNEXPECTED_PUBLIC_FLAG_ENABLED"));
const siteBroken={...base,marketing:{...marketing,http:404}};
assert(decide(siteBroken,{expectV66:true}).reasons.includes("HOSTING_UNREACHABLE"));
console.log("PASS: stale Hosting, undeployed callable, unexpected Public flags and missing sites are detected");
console.log("RESULT: PACKTOOK V6.7 live deployment probe offline QA PASS (no network calls).");
