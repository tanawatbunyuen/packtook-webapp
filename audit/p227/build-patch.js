"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.resolve(__dirname,"../..");
const src=fs.readFileSync(path.join(root,"audit/p226/probe/index.js"),"utf8");
const old='const COL="__g02_iam_boundary_probe__";';
const next='const COL="g02_iam_boundary_probe";';
assert.equal(src.split(old).length,2);
assert(!src.includes(next));
const patched=src.replace(old,next);
assert.equal(patched.replace(next,old),src);
