assert(!/(?:dbNamed|dbDefault|db|snap)\.(?:set|update|delete|create|add|runTransaction)\(/.test(patched));
const out=path.join(__dirname,"probe");
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,"index.js"),patched);
fs.copyFileSync(path.join(root,"audit/p226/probe/package.json"),path.join(out,"package.json"));
