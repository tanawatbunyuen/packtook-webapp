'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'p140-firebase-emulator.json'),'utf8'));
for(const key of ['firestore','auth','hub','logging'])assert.equal(cfg.emulators[key].host,'127.0.0.1');
assert.equal(cfg.emulators.firestore.port,18080);
assert.equal(cfg.emulators.auth.port,19099);
assert.equal(cfg.emulators.hub.port,14400);
assert.equal(cfg.emulators.logging.port,4500);
assert.equal(cfg.emulators.ui.enabled,false);
assert.equal(cfg.firestore.rules,'p140-firestore-deny-all.rules');
assert(!Object.hasOwn(cfg.emulators,'functions'));
const sh=fs.readFileSync(path.join(__dirname,'p141-demo-emulator-start.sh'),'utf8');
assert(sh.includes('for port in 18080 19099 14400 4500; do'));
assert(sh.includes('p=[18080,19099]'));
assert(!sh.includes('p=[18080,19099,14400,4500]'));
