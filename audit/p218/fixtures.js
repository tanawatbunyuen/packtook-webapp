"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {stage,BIN_DIR,sha}=require("./prepare");
const {EXPECTED_CANDIDATE}=require("../p190/reconcile");
const dir=path.resolve(__dirname,"../..",BIN_DIR);
let n=0;function t(s,fn){fn();n++;console.log("P218_"+s+"=PASS")}
const run=()=>stage({target:"local-fixture-only",oldSourceSha256:"25d4550e989b4a4a88eacc011db8f6733a2f3cd322d09db0e33168541df15cd3"});
t("BUILD_OUTPUT_DIR_NOT_PREEXISTING",()=>assert.equal(fs.existsSync(dir),false));
const out=run();
t("REPAIR_BUNDLE_CREATED",()=>assert.equal(out.state,"CANDIDATE_PREPARED_FOR_OFFLINE_REVIEW"));
t("PIN_MATCHED",()=>assert.equal(out.actualCandidateSha256,EXPECTED_CANDIDATE));
t("OPERATOR_STAGING_SOURCE_MISMATCH",()=>assert.equal(out.operatorReportedStagingMatchesCandidate,false));
t("NO_PRODUCTION_Writes",()=>assert.equal(out.deploymentPerformed,false));
t("NO_G02_CLOSURE",()=>assert.equal(out.g02Decision,"NO_GO"));
t("NO_PUBLIC_SIGNUP",()=>assert.equal(out.publicSignup,"KEEP_CLOSED"));
t("CANDIDATE_FILE_PRESENT",()=>assert(fs.statSync(path.join(dir,"index.js")).isFile()));
t("CANDIDATE_FILE_SHA256",()=>assert.equal(sha(fs.readFileSync(path.join(dir,"index.js"))),EXPECTED_CANDIDATE));
t("PACKAGE_FILE_PRESENT",()=>assert(fs.statSync(path.join(dir,"package.json")).isFile()));
t("MANIFEST_FILE_PRESENT",()=>assert(fs.statSync(path.join(dir,"manifest.json")).isFile()));
t("MANIFEST_DEPLOY_FORBIDDEN",()=>assert.equal(JSON.parse(fs.readFileSync(path.join(dir,"manifest.json"))).deployForbidden,true));
t("MANIFEST_SHA_PIN",()=>assert.equal(JSON.parse(fs.readFileSync(path.join(dir,"manifest.json"))).candidateSha256,EXPECTED_CANDIDATE));
t("NO_FIREBASE_CONFIG_IN_BUNDLE",()=>assert.equal(fs.existsSync(path.join(dir,"firebase.json")),false));
t("NO_CREDENTIALS_IN_BUNDLE",()=>assert.equal(fs.existsSync(path.join(dir,".env")),false));
t("ONLY_THREE_BUNDLE_FILES",()=>assert.deepEqual(fs.readdirSync(dir).sort(),["index.js","manifest.json","package.json"]));
t("BLOCK_SECOND_BUILD_TO_PREVENT_OVERWRITE",()=>assert.throws(run,/P218_OUTPUT_ALREADY_EXISTS_FAIL_CLOSED/));
t("BLOCK_UNKNOWN_TARGET",()=>{const r=stage({target:"packtook-staging"});assert.equal(r.state,"BLOCKED");assert(r.issueCodes.includes("UNAUTHORIZED_BUILD_TARGET"))});
t("BLOCK_WRONG_SOURCE_HASH",()=>{const r=stage({target:"offline-operator-review",oldSourceSha256:"wrong"});assert.equal(r.state,"BLOCKED")});
t("BLOCK_UNKNOWN_REGISTRY_ASSERTION",()=>{const r=stage({target:"offline-operator-review",expectedImage:"PRESENT"});assert.equal(r.state,"BLOCKED")});
t("NO_STAGING_CLOUD_CALLS",()=>assert.equal(out.noStagingCloudCalls,true));
t("NO_INDEPENDENT_APPROVAL",()=>assert.equal(out.independentSecurityApproval,false));
t("RELEASE_REMAINS_NO_GO",()=>assert.equal(out.releaseDecision,"NO_GO_RELEASE"));
t("NO_AUTO_DEPLOY",()=>assert.equal(out.deployDecision,"NO_GO_DEPLOY"));
console.log("P218_STAGING_REPAIR_BUNDLE_FIXTURES="+n+"/"+n+"_PASS");
console.log("P218_BUNDLE_READY_FOR_OFFLINE_REVIEW=TRUE");
console.log("P218_STAGING_DEPLOYED=FALSE G02_NO_GO=TRUE");
