"use strict";
const assert=require("node:assert/strict");
const {emailDigest}=require("../../functions/operator-domain-v1.cjs");
const p=require("../../functions/tenant-credit-transaction-policy-v1.cjs");
const owner={actorUid:"owner001",accountId:"owner001",role:"admin"};
const op={actorUid:"operator002",accountId:"owner001",role:"operator"};
const other={actorUid:"operator003",accountId:"owner003",role:"operator"};
const membership={uid:op.actorUid,accountId:op.accountId,status:"active",role:"operator",emailHash:emailDigest("operator@example.com")};
const now=Date.now();let checks=0;
function yes(fn){assert.equal(fn(),true);checks++}
function no(fn,code){assert.throws(fn,e=>e instanceof p.PolicyDenied&&e.message===code);checks++}
yes(()=>p.assertTransactionMembership(owner,null));
yes(()=>p.assertTransactionMembership(op,membership,"operator@example.com"));
no(()=>p.assertTransactionMembership(op,null,"operator@example.com"),"MEMBERSHIP_REVOKED_OR_MISMATCH");
no(()=>p.assertTransactionMembership(op,{...membership,status:"revoked"},"operator@example.com"),"MEMBERSHIP_REVOKED_OR_MISMATCH");
no(()=>p.assertTransactionMembership(op,membership,"attacker@example.com"),"MEMBERSHIP_REVOKED_OR_MISMATCH");
no(()=>p.assertTransactionMembership(other,membership,"operator@example.com"),"MEMBERSHIP_REVOKED_OR_MISMATCH");
no(()=>p.assertTransactionMembership({...owner,accountId:"other"} ,null),"ADMIN_OWNER_MISMATCH");
no(()=>p.assertTransactionMembership(owner,membership),"OWNER_HAS_OPERATOR_MEMBERSHIP");
assert.deepEqual(p.assertReservationCreate(op,membership,"operator@example.com",{accountOwnerUid:"owner001"}),{recordedBy:"operator002",accountId:"owner001"});checks++;
no(()=>p.assertReservationCreate(op,membership,"operator@example.com",{accountOwnerUid:"owner003"}),"TENANT_ACCOUNT_MISMATCH");
no(()=>p.assertReservationCreate(op,membership,"operator@example.com",{accountOwnerUid:"owner001",recordingExists:true}),"OPERATION_ALREADY_EXISTS");
const recording={recordedBy:"operator002",accountId:"owner001",status:"reserved",operationId:"operation0000000001"};
const fin={accountOwnerUid:"owner001",recording,operationId:recording.operationId};
yes(()=>p.assertFinalization(op,membership,"operator@example.com",fin));
no(()=>p.assertFinalization(op,{...membership,status:"revoked"},"operator@example.com",fin),"MEMBERSHIP_REVOKED_OR_MISMATCH");
no(()=>p.assertFinalization(owner,null,undefined,fin),"RECORDING_ACTOR_MISMATCH");
no(()=>p.assertFinalization(op,membership,"operator@example.com",{...fin,recording:{...recording,recordedBy:"operator003"}}),"RECORDING_ACTOR_MISMATCH");
no(()=>p.assertFinalization(op,membership,"operator@example.com",{...fin,recording:{...recording,status:"completed"}}),"RECORDING_NOT_RESERVED_OR_TENANT_MISMATCH");
no(()=>p.assertFinalization(op,membership,"operator@example.com",{...fin,recording:{...recording,accountId:"owner003"}}),"RECORDING_NOT_RESERVED_OR_TENANT_MISMATCH");
no(()=>p.assertFinalization(op,membership,"operator@example.com",{...fin,operationId:"not-original"}),"RECORDING_OPERATION_MISMATCH");
const request={id:"request001",accountId:"owner001",status:"approved",requestedBy:"operator002",barcode:"ABC",approvalId:"approval001"};
const approval={id:"approval001",requestId:"request001",accountId:"owner001",status:"approved",requestedBy:"operator002",barcode:"ABC",expiresAtMs:now+50000};
const arg={approval,request,barcode:"ABC",nowMs:now};
yes(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",arg));
no(()=>p.assertDuplicateApprovalUse(owner,null,undefined,arg),"OPERATOR_APPROVAL_REQUIRED");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,approval:{...approval,status:"consumed"}}),"APPROVAL_NOT_AVAILABLE");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,request:{...request,status:"consumed"}}),"APPROVAL_NOT_AVAILABLE");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,request:{...request,accountId:"other"}}),"APPROVAL_TENANT_OR_ACTOR_MISMATCH");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,approval:{...approval,requestedBy:"operator003"}}),"APPROVAL_TENANT_OR_ACTOR_MISMATCH");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,request:{...request,approvalId:"other"}}),"APPROVAL_REQUEST_LINK_MISMATCH");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,barcode:"OTHER"}),"APPROVAL_BARCODE_MISMATCH");
no(()=>p.assertDuplicateApprovalUse(op,membership,"operator@example.com",{...arg,nowMs:now+60000}),"APPROVAL_EXPIRED");
no(()=>p.assertDuplicateApprovalUse(op,{...membership,status:"revoked"},"operator@example.com",arg),"MEMBERSHIP_REVOKED_OR_MISMATCH");
assert.equal(checks,28);
